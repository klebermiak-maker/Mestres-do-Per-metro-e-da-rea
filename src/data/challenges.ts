// Helper to generate rectangle cells
function createRectCells(w: number, h: number, offsetX = 0, offsetY = 0): GridCell[] {
  const cells: GridCell[] = [];
  for (let y = 0; y < h; y++) {
    for (let x = 0; x < w; x++) {
      cells.push({ x: x + offsetX, y: y + offsetY });
    }
  }
  return cells;
}

